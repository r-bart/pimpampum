const headerLines = [
  'Generated by scripts/generate-state-vocabulary.mjs from the table inside it. Do not edit;',
  'change the table, run `npm run generate:state-vocabulary` and commit the result.',
];

function quote(value) {
  return `"${String(value).replace(/\\/gu, '\\\\').replace(/"/gu, '\\"')}"`;
}

function labelFor(state, surface) {
  return state[surface] ?? state.label;
}

/** One array entry per line, indented four spaces, with a trailing comma on every line but the last. */
function list(entries) {
  return entries.map((entry, index) => `    ${entry}${index === entries.length - 1 ? '' : ','}`);
}

function isLabelled(domain) {
  return domain.states.every((state) => typeof state.label === 'string');
}

export function renderQml(vocabulary = stateVocabulary) {
  const lines = [...headerLines.map((line) => `// ${line}`), 'import QtQuick', '', 'QtObject {'];
  vocabulary.forEach((domain, index) => {
    if (index > 0) lines.push('');
    lines.push(`  // ${domain.description}`);
    lines.push(`  readonly property var ${domain.key}States: [`);
    lines.push(...list(domain.states.map((state) => quote(state.id))));
    lines.push('  ]');
    if (!isLabelled(domain)) return;
    lines.push(`  readonly property var ${domain.key}StateLabels: ({`);
    domain.states.forEach((state, position) => {
      const separator = position === domain.states.length - 1 ? '' : ',';
      lines.push(`    ${quote(state.id)}: ${quote(labelFor(state, 'omarchy'))}${separator}`);
    });
    lines.push('  })');
    lines.push(`  readonly property var ${domain.key}Labels: [`);
    lines.push(...list(domain.states.map((state) => quote(labelFor(state, 'omarchy')))));
    lines.push('  ]');
  });
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

export function renderSwift(vocabulary = stateVocabulary) {
  const lines = [...headerLines.map((line) => `// ${line}`), 'import Foundation'];
  for (const domain of vocabulary) {
    lines.push('', `/// ${domain.description}`);
    lines.push(`enum ${domain.swiftType}: String, Codable, CaseIterable, Sendable {`);
    for (const state of domain.states) lines.push(`  case ${state.id}`);
    if (isLabelled(domain)) {
      lines.push(
        '',
        '  /// The line the native surfaces show for this state.',
        '  var label: String {',
      );
      lines.push('    switch self {');
      for (const state of domain.states) {
        lines.push(`    case .${state.id}: ${quote(labelFor(state, 'macos'))}`);
      }
      lines.push('    }', '  }');
    }
    lines.push('}');
  }
  return `${lines.join('\n')}\n`;
}

export function renderAll(vocabulary = stateVocabulary) {
  return { qml: renderQml(vocabulary), swift: renderSwift(vocabulary) };
}

/** Returns the generated files whose committed bytes differ from the table, with a reason. */
export function checkStateVocabulary(root = repositoryRoot) {
  const drift = [];
  for (const [kind, rendered] of Object.entries(renderAll())) {
    const path = join(root, generatedFiles[kind]);
    let committed;
    try {
      committed = readFileSync(path, 'utf8');
    } catch {
      drift.push(`${generatedFiles[kind]}: missing`);
      continue;
    }
    if (committed !== rendered) drift.push(`${generatedFiles[kind]}: differs from the table`);
  }
  return drift;
}

export function writeStateVocabulary(root = repositoryRoot) {
  const written = [];
  for (const [kind, rendered] of Object.entries(renderAll())) {
    writeFileSync(join(root, generatedFiles[kind]), rendered);
    written.push(generatedFiles[kind]);
  }
  return written;
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
  const argument = process.argv[2];
  if (argument !== undefined && argument !== '--check') {
    process.stderr.write(`Unknown argument ${argument}; use --check or no argument.\n`);
    process.exit(2);
  }
  if (argument === '--check') {
    const drift = checkStateVocabulary();
    if (drift.length > 0) {
      process.stderr.write(
        `State vocabulary drift; run npm run generate:state-vocabulary and commit:\n${drift
          .map((line) => `  - ${line}`)
          .join('\n')}\n`,
      );
      process.exit(1);
    }
    process.stdout.write('State vocabulary matches the generated QML and Swift files.\n');
  } else {
    for (const file of writeStateVocabulary()) process.stdout.write(`wrote ${file}\n`);
  }
}
