#!/usr/bin/env node

// The one source of the state names and user-facing labels the native surfaces share. The Omarchy
// plugin (`StateVocabulary.qml`) and the macOS app (`StateVocabulary.swift`) are generated from the
// table below and committed; `--check` fails when either committed file drifts from the table.
//
//   node scripts/generate-state-vocabulary.mjs          # write both files
//   node scripts/generate-state-vocabulary.mjs --check  # exit 1 when a committed file differs
//
// A state carries `id` (the wire name the daemon and the CLI emit) and, for labelled domains, the
// `label` both surfaces render. Where the product deliberately words one surface differently, the
// entry names that surface (`omarchy`, `macos`) and the generator emits that variant there. The
// overview statuses carry no label: the bar and the menu-bar item render display states that mix
// them with connection failures, and those presentation tables stay where they are.

